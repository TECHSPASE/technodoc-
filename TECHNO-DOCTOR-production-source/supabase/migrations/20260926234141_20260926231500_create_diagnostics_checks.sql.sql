/*
# Create diagnostics_checks table (no auth, shared data)

1. New Tables
- `diagnostics_checks`
  - `id` (uuid, primary key)
  - `category` (text, not null) — one of the app's 9 equipment categories
  - `brand` (text, nullable) — optional brand-specific note
  - `symptom` (text, not null) — what the customer reports
  - `checks` (text, not null) — step-by-step what to check (newline-separated)
  - `cause` (text, nullable) — most probable cause
  - `solution` (text, nullable) — recommended fix
  - `created_at` (timestamp, default now())
2. Security
- Enable RLS, allow anon + authenticated SELECT (read-only reference data).
3. Notes
- Seeded with typical fault-finding playbooks per category.
*/

CREATE TABLE IF NOT EXISTS diagnostics_checks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category text NOT NULL,
  brand text,
  symptom text NOT NULL,
  checks text NOT NULL,
  cause text,
  solution text,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE diagnostics_checks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_diagnostics" ON diagnostics_checks;
CREATE POLICY "anon_select_diagnostics" ON diagnostics_checks
FOR SELECT TO anon, authenticated USING (true);

